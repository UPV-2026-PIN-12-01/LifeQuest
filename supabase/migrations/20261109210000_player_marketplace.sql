CREATE TABLE public.player_inventory (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  character_id bigint NOT NULL REFERENCES public.character_stats(id) ON DELETE CASCADE,
  catalog_id text NOT NULL,
  slot text NOT NULL,
  level integer NOT NULL CHECK (level >= 1),
  quantity integer NOT NULL CHECK (quantity >= 1),
  equipped boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT player_inventory_potions_cannot_be_equipped CHECK (NOT equipped OR slot <> 'Poción')
);

CREATE UNIQUE INDEX player_inventory_one_equipped_item_per_slot
  ON public.player_inventory(character_id, slot)
  WHERE equipped;

CREATE INDEX player_inventory_character_id_idx
  ON public.player_inventory(character_id);

ALTER TABLE public.player_inventory ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.player_inventory TO postgres, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.player_inventory_id_seq TO postgres, service_role;
