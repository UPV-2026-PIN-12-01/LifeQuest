-- XP, rewards and task status are written only by the backend (postgres role, which bypasses RLS).
-- Before this, a logged-in user could PATCH their own character_stats or rewards through the Supabase REST API.
DROP POLICY IF EXISTS "Modificar solo mis propios stats" ON "public"."character_stats";

DROP POLICY IF EXISTS "Ver y reclamar mis propias recompensas" ON "public"."rewards";
CREATE POLICY "Ver mis propias recompensas" ON "public"."rewards"
  FOR SELECT
  TO "authenticated"
  USING ((user_id = public.get_current_user_id()));

DROP POLICY IF EXISTS "Gestionar mis propias tareas" ON "public"."tasks";
CREATE POLICY "Ver mis propias tareas" ON "public"."tasks"
  FOR SELECT
  TO "authenticated"
  USING ((user_id = public.get_current_user_id()));

-- One check-in per task: started_at is the check-in, ended_at the check-out, and focused_seconds
-- counts only the time between heartbeats the page sent while it was visible.
CREATE TABLE IF NOT EXISTS "public"."task_sessions" (
  "id"                bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "task_id"           bigint                   NOT NULL,
  "user_id"           bigint                   NOT NULL,
  "started_at"        timestamp with time zone NOT NULL DEFAULT now(),
  "last_heartbeat_at" timestamp with time zone NOT NULL DEFAULT now(),
  "focused_seconds"   bigint                   NOT NULL DEFAULT 0,
  "ended_at"          timestamp with time zone,
  CONSTRAINT "task_sessions_pkey" PRIMARY KEY (id),
  CONSTRAINT "task_sessions_task_id_key" UNIQUE (task_id),
  CONSTRAINT "task_sessions_task_id_fkey" FOREIGN KEY (task_id) REFERENCES public.tasks(id) ON DELETE CASCADE,
  CONSTRAINT "task_sessions_user_id_fkey" FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE,
  CONSTRAINT "chk_task_sessions_focus" CHECK ((focused_seconds >= 0)),
  CONSTRAINT "chk_task_sessions_end" CHECK (((ended_at IS NULL) OR (ended_at >= started_at)))
);

ALTER TABLE "public"."task_sessions"
  ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Ver mis propias sesiones" ON "public"."task_sessions"
  FOR SELECT
  TO "authenticated"
  USING ((user_id = public.get_current_user_id()));

-- The daily XP cap sums the rewards a user claimed today.
CREATE INDEX IF NOT EXISTS "rewards_user_id_claimed_at_idx" ON "public"."rewards" (user_id, claimed_at);
